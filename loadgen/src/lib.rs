    #[test]
    fn the_deep_flow_mixes_commands_in_the_documented_proportions() {
        // Skip the first 20,000 commands: the generator reaches its cap of live orders after
        // about 12,000, and only then does it start cancelling.
        let config = FlowConfig::deep();
        let mut flow = SyntheticFlow::new(config);
        let steady: Vec<Command> = flow.by_ref().skip(20_000).take(50_000).collect();
        assert!(flow.live.len() <= config.max_live_orders);

        let mut places = 0;
        let mut iocs = 0;
        let mut gtcs: usize = 0;
        let mut post_only = 0;
        let mut cancels = 0;
        let mut modifies = 0;
        for command in &steady {
            match command {
                Command::PlaceOrder(p) if p.tif == TimeInForce::Ioc => {
                    places += 1;
                    iocs += 1;
                    assert!(!p.post_only, "an IOC taker is never post-only");
                }
                Command::PlaceOrder(p) => {
                    places += 1;
                    gtcs += 1;
                    post_only += usize::from(p.post_only);
                }
                Command::CancelOrder(_) => cancels += 1,
                Command::ModifyOrder(_) => modifies += 1,
                other => panic!("unexpected command {other:?}"),
            }
        }
        let n = steady.len();
        // Expected (FlowConfig::deep docs): 10% modifies; the other 90% split so that
        // cancels equal GTC places, which are 95% of places: 46.2% places, 43.8% cancels.
        let near = |actual: f64, expected: f64| (actual - expected).abs() < 1.5;
        assert!(near(percent(modifies, n), 10.0), "modifies {:.1}%", percent(modifies, n));
        assert!(near(percent(places, n), 46.2), "places {:.1}%", percent(places, n));
        assert!(near(percent(cancels, n), 43.8), "cancels {:.1}%", percent(cancels, n));
        assert!(gtcs.abs_diff(cancels) <= 1, "at the cap, every resting place replaces an order");
        assert!(near(percent(iocs, places), 5.0), "IOC {:.1}% of places", percent(iocs, places));
        assert!(near(percent(post_only, gtcs), 20.0), "post-only {:.1}% of GTC", percent(post_only, gtcs));
    }

    #[test]
    fn deep_quotes_rest_on_their_own_side_mostly_near_mid_and_takers_cross() {
        let config = FlowConfig::deep();
        let (mut near_mid, mut far_out) = (0, 0);
        for command in SyntheticFlow::new(config).take(50_000) {
            let Command::PlaceOrder(p) = command else { continue };
            let distance = (p.price - config.mid).abs();
            assert!(distance <= config.half_width);
            assert!((1..=config.max_qty).contains(&p.qty));
            // Resting bids at or below mid, resting asks at or above; takers the other way.
            let below_mid = p.price <= config.mid;
            let above_mid = p.price >= config.mid;
            match (p.side, p.tif) {
                (Side::Buy, TimeInForce::Gtc) | (Side::Sell, TimeInForce::Ioc) => assert!(below_mid, "{p:?}"),
                (Side::Sell, TimeInForce::Gtc) | (Side::Buy, TimeInForce::Ioc) => assert!(above_mid, "{p:?}"),
            }
            if distance <= 10 {
                near_mid += 1;
            } else if distance > 50 {
                far_out += 1;
            }
        }
        // Geometric at 95% per tick: 43% of orders within 10 ticks, 7% beyond 50.
        assert!(near_mid > 4 * far_out, "{near_mid} within 10 ticks, {far_out} beyond 50");
    }

    #[test]
    fn deep_modifies_send_the_orders_total_size_as_the_client_last_set_it() {
        // Follow each order's total size from its place through its modifies. A modify
        // that moves the price repeats that total: it is not reduced by fills the client
        // can't see. One that keeps the price sets a new total.
        let config = FlowConfig::deep();
        let mut last_sent: HashMap<OrderId, (Price, Qty)> = HashMap::new();
        let (mut repriced, mut resized) = (0, 0);
        for command in SyntheticFlow::new(config).take(50_000) {
            match command {
                Command::PlaceOrder(p) if p.tif == TimeInForce::Gtc => {
                    last_sent.insert(p.order_id, (p.price, p.qty));
                }
                Command::PlaceOrder(_) => {}
                Command::CancelOrder(c) => {
                    last_sent.remove(&c.order_id).expect("cancels only orders it placed");
                }
                Command::ModifyOrder(m) => {
                    let (price, size) = last_sent[&m.order_id];
                    if m.new_price != price {
                        assert_eq!(m.new_size, size, "a price move keeps the total size");
                        repriced += 1;
                    } else {
                        assert!((1..=config.max_qty).contains(&m.new_size));
                        resized += 1;
                    }
                    last_sent.insert(m.order_id, (m.new_price, m.new_size));
                }
                other => panic!("unexpected command {other:?}"),
            }
        }
        assert!(repriced > 1_000 && resized > 1_000, "{repriced} price moves, {resized} resizes");
    }

    #[test]
    fn the_deep_flow_keeps_thousands_of_orders_resting_on_many_levels() {
        let config = FlowConfig::deep();
        let mut book =
            Book::new(BookConfig { market: config.market, min_price: 1, max_price: 2 * config.mid });
        let mut events: Vec<Event> = Vec::new();
        for command in SyntheticFlow::new(config).take(60_000) {
            match command {
                Command::PlaceOrder(p) => book.place(&p, &mut events),
                Command::CancelOrder(c) => book.cancel(c.order_id, &mut events),
                Command::ModifyOrder(m) => book.modify(m.order_id, m.new_price, m.new_size, &mut events),
                other => panic!("unexpected command {other:?}"),
            }
            events.clear();
        }
        let snapshot = book.snapshot();
        let resting = snapshot.bids.len() + snapshot.asks.len();
        assert!((5_000..=20_000).contains(&resting), "{resting} resting orders");
        for side in [&snapshot.bids, &snapshot.asks] {
            let per_level = orders_per_level(side);
            assert!(per_level.len() >= 50, "only {} levels on one side", per_level.len());
            // Dense near the top: the best 10 levels hold more orders than all the levels
            // beyond the 50th.
            let top: usize = per_level[..10].iter().sum();
            let tail: usize = per_level[50..].iter().sum();
            assert!(top > tail, "{top} orders on the best 10 levels, {tail} beyond the 50th");
        }
    }

    /// The number of orders on each level of one side of a snapshot, best level first. The
    /// snapshot lists orders best price first, so each level's orders are adjacent.
    fn orders_per_level(side: &[RestingOrder]) -> Vec<usize> {
        let mut counts = Vec::new();
        let mut last_price = None;
        for order in side {
            if last_price == Some(order.price) {
                *counts.last_mut().expect("a level was started") += 1;
            } else {
                counts.push(1);
                last_price = Some(order.price);
            }
        }
        counts
    }
