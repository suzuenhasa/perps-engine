/// SplitMix64: a tiny, well-known pseudo-random generator (Steele, Lea and Flood, 2014).
/// Good statistical quality for simulation; not for cryptography.
#[derive(Clone, Debug)]
pub struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    pub fn new(seed: u64) -> Self {
        SplitMix64 { state: seed }
    }

    pub fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// A value in `0..n`. The tiny modulo bias is irrelevant for load generation.
    pub fn below(&mut self, n: u64) -> u64 {
        self.next_u64() % n
    }

    /// A value in `lo..=hi`.
    pub fn in_range(&mut self, lo: i64, hi: i64) -> i64 {
        lo + self.below((hi - lo + 1) as u64) as i64
    }

    /// True with probability `percent / 100`.
    pub fn chance(&mut self, percent: u64) -> bool {
        self.below(100) < percent
    }
}

/// How order prices are spread around mid.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Prices {
    /// Uniform in `mid - half_width ..= mid + half_width`, whatever the side, so about half
    /// of the orders cross the spread and trade on arrival. The M0 flow.
    Uniform,
    /// Resting orders sit on their own side of mid, bids at `mid - d` and asks at `mid + d`,
    /// with the distance `d` skewed towards 0: starting from 0, each further tick is taken
    /// with probability `further_tick_percent` / 100, up to `half_width` (a geometric
    /// distribution, mean `p / (1 - p)` ticks). So the book is dense near the top and thins
    /// out further away.
    ///
    /// At `d = 0` bids and asks meet: a quote at mid trades if the other side holds the mid,
    /// or is rejected if it is post-only. An IOC taker gets a distance drawn the same way
    /// but on the other side of mid, so it crosses the spread and takes what rests up to
    /// its price, usually the first level or two.
    Skewed { further_tick_percent: u64 },
}

/// Shape of the flow. `Default` is the M0 flow; [`FlowConfig::deep`] the deep-book flow.
#[derive(Clone, Copy, Debug)]
pub struct FlowConfig {
    pub seed: u64,
    pub market: MarketId,
    /// Accounts are numbered `1..=accounts`.
    pub accounts: AccountId,
    pub mid: Price,
    /// No order is priced further than this from `mid`. With the default
    /// [`Prices::Uniform`], prices are uniform in `mid - half_width ..= mid + half_width`,
    /// so roughly half of the orders cross the spread and trade.
    pub half_width: Price,
    /// Every order's size is uniform in `1..=max_qty` lots.
    pub max_qty: Qty,
    /// Share of commands that cancel a random earlier order instead of placing a new one.
    pub cancel_percent: u64,

    // Added in Milestone 1. Each default turns the option off, which keeps the M0 stream.
    /// How prices are spread around `mid`. Default: [`Prices::Uniform`].
    pub prices: Prices,
    /// Share of the remaining commands (those that aren't random cancels) that modify a
    /// random earlier order. Default 0.
    pub modify_percent: u64,
    /// The most orders the generator keeps live, as far as it knows. At this many, a
    /// command that would have been a place cancels a random live order instead, the way
    /// a market maker keeps a fixed number of quotes out. The book then settles at a
    /// steady depth rather than growing. Default `usize::MAX`: no cap.
    pub max_live_orders: usize,
    /// Share of places that are IOC takers. Default 0: every order is GTC.
    pub ioc_percent: u64,
    /// Share of the other places (the GTC ones) that are post-only. Default 0.
    pub post_only_percent: u64,
}

impl Default for FlowConfig {
    fn default() -> Self {
        FlowConfig {
            seed: 1,
            market: 1,
            accounts: 100,
            mid: 10_000,
            half_width: 20,
            max_qty: 10,
            cancel_percent: 40,
            prices: Prices::Uniform,
            modify_percent: 0,
            max_live_orders: usize::MAX,
            ioc_percent: 0,
            post_only_percent: 0,
        }
    }
}

impl FlowConfig {
    /// The deep-book flow (Milestone 1): a book with thousands of resting orders, where a
    /// linear scan gets slow and the fast book has to show it doesn't.
    ///
    /// These are **assumed parameters** (INFO.md section 7), chosen to be plausible, not
    /// calibrated against real data (that is "Later", INFO.md section 12.4):
    /// - **1,000 accounts, about 10 orders live each** (`max_live_orders` 10,000). Once the
    ///   generator has 10,000 orders out, each new one replaces a random old one. So cancels
    ///   come at random ages rather than at a fixed lifetime, and in steady state there are
    ///   as many cancels as resting places: a cancel-heavy flow, as on real venues. There
    ///   are no other cancels (`cancel_percent` 0).
    /// - **Distance from mid**: 95% chance of each further tick. The mean distance is 19
    ///   ticks; about 5% of quotes land on each of the first few levels, and 0.6% in all
    ///   beyond 100 ticks. The 250-tick limit is practically never reached, so no orders
    ///   pile up at it.
    /// - **10% modifies**: half move the order to a new distance from mid, half set a new
    ///   total size.
    /// - **5% of places are IOC takers** (about 2% of commands), so there is a fill for
    ///   about one command in 20: real venues see many orders per trade. Each fill leaves
    ///   the generator an order it will later cancel or modify in vain, so the taker share
    ///   sets the reject share: about 5% of commands (7% with 10% takers).
    /// - **20% of resting places are post-only**, as market makers use them.
    /// - **Sizes 1-10 lots** for every order, as in the M0 flow, and the same fixed mid of
    ///   10,000 ticks, so both flows fit the same book configuration. A moving fair value
    ///   is Milestone 3.
    ///
    /// The generator reaches its 10,000 live orders after about 12,000 commands. After
    /// that, the mix is about 46% places, 44% cancels and 10% modifies. Orders that filled
    /// without the generator knowing stay on its list until it happens to cancel them, so
    /// the book itself holds fewer: about 9,100 orders on 110-130 levels per side after
    /// 100,000 commands, and about the same from then on.
    pub fn deep() -> Self {
        FlowConfig {
            seed: 1,
            market: 1,
            accounts: 1_000,
            mid: 10_000,
            half_width: 250,
            max_qty: 10,
            cancel_percent: 0,
            prices: Prices::Skewed { further_tick_percent: 95 },
            modify_percent: 10,
            max_live_orders: 10_000,
            ioc_percent: 5,
            post_only_percent: 20,
        }
    }
}

/// An order the generator has placed and not cancelled, as the client last sent it. It
/// may have filled since: the generator never sees the book.
#[derive(Clone, Copy, Debug)]
struct LiveOrder {
    order_id: OrderId,
    side: Side,
    price: Price,
    /// The order's total size as the client last set it (by the place or a modify). Fills
    /// don't reduce it, since the client doesn't see them.
    size: Qty,
}

/// An endless, deterministic stream of place, cancel and modify commands. Each command is
/// chosen in this order (see [`FlowConfig`] for each option):
/// 1. With no live orders, place one.
/// 2. With probability `cancel_percent`, cancel a random live order.
/// 3. Otherwise, with probability `modify_percent`, modify a random live order.
/// 4. Otherwise, at `max_live_orders`, cancel a random live order to make room.
/// 5. Otherwise, place an order.
///
/// It is open-loop (module docs): some cancels and modifies target orders that have
/// already filled, and the book rejects those as `UnknownOrder`, as real flow would.
#[derive(Clone, Debug)]
pub struct SyntheticFlow {
    config: FlowConfig,
    rng: SplitMix64,
    /// Next sequence number per account (index 0 unused).
    next_seq: Vec<u32>,
    /// GTC orders placed and not yet cancelled by this generator.
    live: Vec<LiveOrder>,
}

impl SyntheticFlow {
    pub fn new(config: FlowConfig) -> Self {
        SyntheticFlow {
            config,
            rng: SplitMix64::new(config.seed),
            next_seq: vec![0; config.accounts as usize + 1],
            live: Vec::new(),
        }
    }

    /// True with probability `percent / 100`, like [`SplitMix64::chance`], except that 0%
    /// draws no random number at all. That is how an option switched off leaves the M0
    /// stream exactly as it was.
    fn roll(&mut self, percent: u64) -> bool {
        percent > 0 && self.rng.chance(percent)
    }

    /// How far from mid to price an order, drawn before its side is known (see
    /// [`SyntheticFlow::price_at`]):
    /// - [`Prices::Uniform`]: a signed offset in `-half_width..=half_width`.
    /// - [`Prices::Skewed`]: a distance in `0..=half_width`, from 0 up, one tick at a time.
    fn draw_offset(&mut self) -> Price {
        let half_width = self.config.half_width;
        match self.config.prices {
            Prices::Uniform => self.rng.in_range(-half_width, half_width),
            Prices::Skewed { further_tick_percent } => {
                let mut distance = 0;
                while distance < half_width && self.rng.chance(further_tick_percent) {
                    distance += 1;
                }
                distance
            }
        }
    }

    /// The price of an order on `side` at `offset` from mid (from `draw_offset`). With
    /// skewed prices, a resting order goes on its own side of mid and a taker on the other.
    fn price_at(&self, side: Side, offset: Price, taker: bool) -> Price {
        let mid = self.config.mid;
        match self.config.prices {
            Prices::Uniform => mid + offset,
            Prices::Skewed { .. } => match (side, taker) {
                // A resting bid, or a sell that crosses down into the bids.
                (Side::Buy, false) | (Side::Sell, true) => mid - offset,
                // A resting ask, or a buy that crosses up into the asks.
                (Side::Sell, false) | (Side::Buy, true) => mid + offset,
            },
        }
    }

    fn next_place(&mut self) -> Command {
        let c = self.config;
        // Account, offset, size and side are the M0 flow's draws, in its order. The options
        // after them draw nothing while off (`roll`), so the default stream is unchanged.
        let account = 1 + self.rng.below(c.accounts as u64) as AccountId;
        self.next_seq[account as usize] += 1;
        let id = order_id(account, self.next_seq[account as usize]);
        let offset = self.draw_offset();
        let qty = self.rng.in_range(1, c.max_qty);
        let side = if self.rng.chance(50) { Side::Buy } else { Side::Sell };
        let taker = self.roll(c.ioc_percent);
        let post_only = !taker && self.roll(c.post_only_percent);

        let price = self.price_at(side, offset, taker);
        // Only a GTC order can rest, so only it can be cancelled or modified later.
        if !taker {
            self.live.push(LiveOrder { order_id: id, side, price, size: qty });
        }
        Command::PlaceOrder(PlaceOrder {
            order_id: id,
            price,
            qty,
            market: c.market,
            side,
            tif: if taker { TimeInForce::Ioc } else { TimeInForce::Gtc },
            post_only,
        })
    }

    fn next_cancel(&mut self) -> Command {
        let i = self.rng.below(self.live.len() as u64) as usize;
        let order = self.live.swap_remove(i);
        Command::CancelOrder(CancelOrder { order_id: order.order_id, market: self.config.market })
    }

    /// Modifies a random live order. Half the time it moves to a new price (a fresh offset
    /// from mid, on its own side) and keeps its total size; otherwise it keeps its price and
    /// gets a new total size.
    ///
    /// Either way, `new_size` is the order's *total* size as the client wants it, never
    /// reduced by fills the client hasn't seen. The book subtracts what has filled
    /// (`command::ModifyOrder`), and removes the order if nothing would be left.
    fn next_modify(&mut self) -> Command {
        let c = self.config;
        let i = self.rng.below(self.live.len() as u64) as usize;
        let mut order = self.live[i];
        if self.rng.chance(50) {
            let offset = self.draw_offset();
            order.price = self.price_at(order.side, offset, false);
        } else {
            order.size = self.rng.in_range(1, c.max_qty);
        }
        self.live[i] = order;
        Command::ModifyOrder(ModifyOrder {
            order_id: order.order_id,
            new_price: order.price,
            new_size: order.size,
            market: c.market,
        })
    }
}

impl Iterator for SyntheticFlow {
    type Item = Command;

    fn next(&mut self) -> Option<Command> {
        let c = self.config;
        let command = if self.live.is_empty() {
            self.next_place()
        } else if self.roll(c.cancel_percent) {
            self.next_cancel()
        } else if self.roll(c.modify_percent) {
            self.next_modify()
        } else if self.live.len() >= c.max_live_orders {
            // At the cap: make room instead of placing.
            self.next_cancel()
        } else {
            self.next_place()
        };
        Some(command)
    }
}

