//! # loadgen
//!
//! Deterministic synthetic order flow for the tests and benchmarks, and (Milestone 3) the
//! open-loop load for the whole pipeline. Two presets, around a fixed mid price, feed the
//! book benchmarks:
//! - [`FlowConfig::default()`], the **Milestone 0 flow**: places and cancels at prices
//!   uniform around mid, so about half of the orders trade on arrival and the book stays
//!   shallow (a few hundred resting orders). It is the stream the M0 baseline was measured
//!   on, and it must never change: a test pins it.
//! - [`FlowConfig::deep()`], the **Milestone 1 deep-book flow**: about 10,000 live orders
//!   from 1,000 accounts, dense near the top of the book and thinning out away from it,
//!   with IOC takers, post-only quotes, cancels and modifies.
//!
//! **Contract.** The same seed and config always produce exactly the same commands, on
//! every machine. That's what makes benchmark runs repeatable and lets a failing run be
//! replayed. Every option added after M0 is off by default and, while off, draws no random
//! numbers, so it can't shift the default stream.
//!
//! **Open loop.** The generator never looks at the book, like a client that doesn't wait
//! for replies. It remembers the orders it placed, not whether they filled, so some of its
//! cancels and modifies hit orders that have already gone. The book rejects those, as it
//! would real flow, and the benchmarks report the rejects.
//!
//! **Milestone 3** (`docs/PIPELINE.md` section 14; `docs/DECISIONS.md` D-027): the load
//! for the whole pipeline, in its own modules. These two flows stay exactly as they were.
//! - [`market_flow`]: the M3 synthetic flow: 67 markets, each with its own fair-value path,
//!   market makers, takers, high-leverage accounts, a thin long-lived layer, and the setup
//!   phases that go through the journal before the timed flow (14.1 to 14.7). And the
//!   Polymarket-shaped flow (D-034): [`market_flow::polymarket`], Polymarket Perps' 88 real
//!   markets traded with the shape of their recorded traffic, into the same kind of plan; its
//!   calibrated profile, [`market_flow::profile`], generated by `tools/calibrate`.
//! - [`keys`]: each account's secp256k1 key, derived from the seed, and `keys.txt` (14.8).
//! - [`presign`]: every client message signed before the run, in parallel, into an arena,
//!   in our nonce scheme or in Polymarket Perps' EIP-712 scheme (5.8); the compact unsigned
//!   arena for pre-verified runs; `presigned.bin` (14.8).
//! - [`schedule`]: when each item is sent: Poisson (or, for debugging, evenly spaced)
//!   arrivals at the offered rate (14.9), or, with `--bursts` (D-034), a Poisson process
//!   whose rate swings each second as Polymarket's recorded message rate did.
//! - [`sender`]: the open-loop sender thread, which never waits for the system: a full
//!   ring drops the message and counts it (14.10).
//!
//! Randomness comes from [`SplitMix64`], written here rather than taken from a crate: it is
//! a dozen lines, fast, and its output is fixed forever, whereas a library's could change
//! between versions (`docs/DECISIONS.md` D-006). There are no floats in what any flow
//! contains, since float functions such as `ln` can round differently on different
//! machines. The only floats are in [`schedule`]: a Poisson gap is `−ln(1 − u) / R`, and
//! bursts multiply the rate by `exp` of normal draws. They can only change *when* a message is
//! sent, never what it says (PIPELINE.md 14.9).

